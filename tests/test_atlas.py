class NexusMatchTests(unittest.TestCase):
    def setUp(self):
        reset_home()
        modlist = "\n".join("+" + n for n in ("Vanilla Scripting Enhancements - BSA Version", "SkyUI", "Twin Mod",
                                              "Nothing Like It", "Plain Mod")) + "\n"
        lib.build_text_list("up", {"modlist.txt": modlist}, {})
        # an MO2 list already knows "Plain Mod" by its Nexus ID, so it isn't searched
        export_modlist.export(make_fake_mo2(TMP / f"mo2-{self._testMethodName}"), "Default", "mo2", use_api=False)
        mods = json.loads((lib.LISTS / "mo2" / "mods.json").read_text("utf-8"))
        for m in mods:
            if m["name"] == "Plain Mod":
                m["key"] = "skyrimspecialedition/5"
        (lib.LISTS / "mo2" / "mods.json").write_text(json.dumps(mods), "utf-8")
        lib.rebuild_index()

    def test_trimmed(self):
        self.assertEqual(nexus_match.trimmed("Vanilla Scripting Enhancements - BSA Version"), "Vanilla Scripting Enhancements")
        self.assertEqual(nexus_match.trimmed("SkyUI_5_2_SE"), "SkyUI")
        self.assertEqual(nexus_match.trimmed("Some Mod (SE)"), "Some Mod")
        self.assertEqual(nexus_match.trimmed("Some Mod v1.2.3"), "Some Mod")
        self.assertEqual(nexus_match.trimmed("X - Y"), "")

    def test_tiers_and_cache(self):
        post, calls = fake_nexus(NEXUS_CATALOG)
        self.assertNotIn("name:plainmod", nexus_match.names_to_lookup("skyrimspecialedition"))
        counts = nexus_match.run("skyrimspecialedition", post=post, pause=0)
        game = nexus_match.load()["games"]["skyrimspecialedition"]
        self.assertEqual((game["name:skyui"]["status"], game["name:skyui"]["id"]), ("auto", 12604))
        self.assertEqual(game["name:twinmod"]["status"], "suggest")  # two mods share the title
        vse = game["name:vanillascriptingenhancementsbsaversion"]
        self.assertEqual((vse["status"], vse["candidates"][0]["id"]), ("suggest", 68139))  # trimmed: never auto
        self.assertEqual(game["name:nothinglikeit"]["status"], "none")
        self.assertEqual(vse["candidates"][0]["summary"], "s")  # markup stripped
        self.assertEqual(counts, {"auto": 1, "suggest": 2, "none": 1})
        # cached: a second run asks Nexus nothing; retry only re-asks the misses
        n = len(calls)
        nexus_match.run("skyrimspecialedition", post=post, pause=0)
        self.assertEqual(len(calls), n)
        nexus_match.run("skyrimspecialedition", retry=True, post=post, pause=0)
        self.assertEqual([v for k, v in calls[n].items() if k != "d"], ["Nothing Like It"])

    def test_user_choices_survive_new_searches(self):
        post, _ = fake_nexus(NEXUS_CATALOG)
        nexus_match.run("skyrimspecialedition", post=post, pause=0)
        nexus_match.set_status("skyrimspecialedition", "name:twinmod", "accept", 2)
        nexus_match.set_status("skyrimspecialedition", "name:skyui", "reject")
        with self.assertRaises(ValueError):
            nexus_match.set_status("skyrimspecialedition", "name:twinmod", "accept", 999)
        with self.assertRaises(KeyError):
            nexus_match.set_status("skyrimspecialedition", "name:unknown", "reject")
        game = nexus_match.load()["games"]["skyrimspecialedition"]
        game["name:twinmod"]["status"] = "accepted"
        nexus_match.run("skyrimspecialedition", retry=True, post=post, pause=0)
        game = nexus_match.load()["games"]["skyrimspecialedition"]
        self.assertEqual((game["name:twinmod"]["status"], game["name:twinmod"]["id"]), ("accepted", 2))
        self.assertEqual(game["name:skyui"]["status"], "rejected")
        nexus_match.set_status("skyrimspecialedition", "name:skyui", "reset")
        self.assertEqual(nexus_match.load()["games"]["skyrimspecialedition"]["name:skyui"]["status"], "suggest")


class ServerTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        reset_home()
        serve.Handler.log_message = lambda *a: None  # keep test output readable
        cls.server = serve.make_server(0)
        cls.port = cls.server.server_address[1]
        threading.Thread(target=cls.server.serve_forever, daemon=True).start()
        cls.mo2 = make_fake_mo2(TMP / "mo2-server")
        cls.session = lib.create_session("Test", "skyrimspecialedition")["name"]
        cls.decisions = lib.session_decisions(cls.session)
        cls.api_decisions = f"/api/decisions?session={cls.session}"

    @classmethod
    def tearDownClass(cls):
        cls.server.shutdown()
        cls.server.server_close()

    def request(self, method, path, body=None, headers=None):
        conn = http.client.HTTPConnection("127.0.0.1", self.port, timeout=60)
        hdrs = {"Host": f"localhost:{self.port}", **(headers or {})}
        data = None
        if body is not None:
            data = json.dumps(body).encode()
            hdrs.setdefault("Content-Type", "application/json")
            hdrs.setdefault("X-Modlist-Atlas", "1")
        conn.putrequest(method, path, skip_host=True, skip_accept_encoding=True)  # raw path, no normalising
        for k, v in hdrs.items():
            conn.putheader(k, v)
        if data is not None:
            conn.putheader("Content-Length", str(len(data)))
        conn.endheaders(data)
        resp = conn.getresponse()
        raw = resp.read()
        conn.close()
        try:
            payload = json.loads(raw)
        except ValueError:
            payload = raw
        return resp.status, payload

    def test_static_allowlist(self):
        self.assertEqual(self.request("GET", "/")[0], 200)
        self.assertEqual(self.request("GET", "/web/app.js")[0], 200)
        self.assertEqual(self.request("GET", "/lists/index.json")[0], 200)
        self.assertEqual(self.request("GET", "/plan/sessions/index.json")[0], 200)
        self.assertEqual(self.request("GET", f"/plan/sessions/{self.session}/decisions.json")[0], 200)
        # never "304 not modified": a file rewritten within the same second would look unchanged
        later = {"If-Modified-Since": "Fri, 01 Jan 2100 00:00:00 GMT"}
        self.assertEqual(self.request("GET", "/plan/sessions/index.json", headers=later)[0], 200)
        for path in ("/.env", "/%2eenv", "/web/../.env", "/web/%2e%2e/.env", "/tools/serve.py", "/README.md",
                     "/lists/", "/lists/../.lists.local.json", "/ENV~1", "/lists/x/ENV~1", "/web/..%5c.env",
                     "/.git/config", "/plan/", "/data/nexus_cache.json", "/plan/decisions.json", "/plan/sessions/",
                     "/plan/sessions/../decisions.before-sessions.json"):
            self.assertEqual(self.request("GET", path)[0], 404, path)

    def test_host_header_and_post_guards(self):
        self.assertEqual(self.request("GET", "/api/status", headers={"Host": "evil.example"})[0], 403)
