def make_fake_mo2(root: Path) -> Path:
    """A minimal MO2 instance: two mods, one separator, categories, INIs with machine paths."""
    mo2 = root / "mo2"
    prof = mo2 / "profiles" / "Default"
    prof.mkdir(parents=True)
    (prof / "modlist.txt").write_text(MO2_MODLIST, "utf-8")
    (prof / "plugins.txt").write_text("*EngineFix.esp\nPlain.esp\n", "utf-8")
    (prof / "Skyrim.ini").write_text("[Display]\nsScreenShotBaseName=F:\\Steam\\Shots\nfGamma=1.0\n", "utf-8")
    (prof / "SkyrimPrefs.ini").write_text('[Display]\nsD3DDevice="Some GPU 9000"\niSize W=2560\n', "utf-8")
    (mo2 / "categories.dat").write_text("42|Bug Fixes|0\n7|Miscellaneous|0\n", "utf-8")
    (mo2 / "nexuscatmap.dat").write_text("42|Bug Fixes|95\n7|Miscellaneous|28\n", "utf-8")
    fix = mo2 / "mods" / "Engine Fix"
    fix.mkdir(parents=True)
    (fix / "meta.ini").write_text(
        "[General]\ngameName=SkyrimSE\nmodid=123\nversion=1.2.0\nnexusCategory=95\n"
        'nexusDescription="Fixes many long-standing engine bugs that crash the game.\\n<br />[b]Details[/b]"\n'
        "notes=check after update\n", "utf-8")
    plain = mo2 / "mods" / "Plain Mod"
    plain.mkdir(parents=True)
    (plain / "meta.ini").write_text("[General]\ngameName=SkyrimSE\nmodid=0\n", "utf-8")
    return mo2


def make_fake_fallout4(root: Path) -> Path:
    """A non-Skyrim MO2 instance: game set in ModOrganizer.ini, one mod without gameName."""
    mo2 = root / "mo2-fo4"
    prof = mo2 / "profiles" / "Default"
    prof.mkdir(parents=True)
    (mo2 / "ModOrganizer.ini").write_text("[General]\ngameName=Fallout 4\n", "utf-8")
    (prof / "modlist.txt").write_text("# MO2\n+Odd Game Mod\n+No Game Mod\n+Weapon Mod\n", "utf-8")
    (prof / "Fallout4.ini").write_text("[Display]\nsScreenShotBaseName=D:\\Games\\Shots\n", "utf-8")
    (prof / "Fallout4Prefs.ini").write_text('[Display]\nsD3DDevice="GPU"\niSize W=1920\n', "utf-8")
    (prof / "Fallout4Custom.ini.BethINIbackup").write_text("[x]\n", "utf-8")
    for name, meta in (("Weapon Mod", "gameName=Fallout4\nmodid=55\n"),
                       ("No Game Mod", "modid=77\n"),
                       ("Odd Game Mod", "gameName=Some New Game\nmodid=9\n")):
        (mo2 / "mods" / name).mkdir(parents=True)
        (mo2 / "mods" / name / "meta.ini").write_text("[General]\n" + meta, "utf-8")
    return mo2


