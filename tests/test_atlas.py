        fix = mods["Engine Fix"]
        self.assertEqual(fix["key"], "skyrimspecialedition/123")
        self.assertEqual(fix["url"], "https://www.nexusmods.com/skyrimspecialedition/mods/123")
        self.assertEqual(fix["category"], "Bug Fixes")
        self.assertFalse(fix["enabled"])
        self.assertEqual(fix["notes"], "check after update")
        self.assertTrue(fix["summary"].startswith("Fixes many long-standing"))
        self.assertEqual(mods["Plain Mod"]["key"], "name:plainmod")
        self.assertIn("sScreenShotBaseName=\n", (out / "profile" / "Skyrim.ini").read_text("utf-8"))
        self.assertIn("sD3DDevice=\n", (out / "profile" / "SkyrimPrefs.ini").read_text("utf-8"))
