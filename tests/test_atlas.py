def make_fake_mo2(root: Path) -> Path:
    """A minimal MO2 instance: two mods, one separator, categories, INIs with machine paths."""
    mo2 = root / "mo2"
    prof = mo2 / "profiles" / "Default"
    prof.mkdir(parents=True)
    (prof / "modlist.txt").write_text(MO2_MODLIST, "utf-8")
    (prof / "plugins.txt").write_text("*EngineFix.esp\nPlain.esp\n", "utf-8")
    (prof / "Skyrim.ini").write_text("[Display]\nsScreenShotBaseName=F:\\Steam\\Shots\nfGamma=1.0\n", "utf-8")
    (prof / "SkyrimPrefs.ini").write_text('[Display]\nsD3DDevice="Some GPU 9000"\niSize W=2560\n', "utf-8")
    (mo2 / "categories.dat").write_text("42|Bug Fixes|0\n7|Miscellaneous|0\n", "utf-8")
    (mo2 / "nexuscatmap.dat").write_text("42|Bug Fixes|95\n7|Miscellaneous|28\n", "utf-8")
    fix = mo2 / "mods" / "Engine Fix"
    fix.mkdir(parents=True)
    (fix / "meta.ini").write_text(
        "[General]\ngameName=SkyrimSE\nmodid=123\nversion=1.2.0\nnexusCategory=95\n"
        'nexusDescription="Fixes many long-standing engine bugs that crash the game.\\n<br />[b]Details[/b]"\n'
        "notes=check after update\n", "utf-8")
    plain = mo2 / "mods" / "Plain Mod"
    plain.mkdir(parents=True)
    (plain / "meta.ini").write_text("[General]\ngameName=SkyrimSE\nmodid=0\n", "utf-8")
    return mo2


def make_fake_fallout4(root: Path) -> Path:
    """A non-Skyrim MO2 instance: game set in ModOrganizer.ini, one mod without gameName."""
    mo2 = root / "mo2-fo4"
    prof = mo2 / "profiles" / "Default"
    prof.mkdir(parents=True)
    (mo2 / "ModOrganizer.ini").write_text("[General]\ngameName=Fallout 4\n", "utf-8")
    (prof / "modlist.txt").write_text("# MO2\n+Odd Game Mod\n+No Game Mod\n+Weapon Mod\n", "utf-8")
    (prof / "Fallout4.ini").write_text("[Display]\nsScreenShotBaseName=D:\\Games\\Shots\n", "utf-8")
    (prof / "Fallout4Prefs.ini").write_text('[Display]\nsD3DDevice="GPU"\niSize W=1920\n', "utf-8")
    (prof / "Fallout4Custom.ini.BethINIbackup").write_text("[x]\n", "utf-8")
    for name, meta in (("Weapon Mod", "gameName=Fallout4\nmodid=55\n"),
                       ("No Game Mod", "modid=77\n"),
                       ("Odd Game Mod", "gameName=Some New Game\nmodid=9\n")):
        (mo2 / "mods" / name).mkdir(parents=True)
        (mo2 / "mods" / name / "meta.ini").write_text("[General]\n" + meta, "utf-8")
    return mo2


def reset_home():
    shutil.rmtree(lib.HOME, ignore_errors=True)
    lib.HOME.mkdir(parents=True)


class CoreTests(unittest.TestCase):
    def setUp(self):
        reset_home()

    def test_parse_modlist_reverses_mo2_order_and_skips_dlc(self):
        rows = list(lib.parse_modlist(MO2_MODLIST.splitlines()))
        self.assertEqual(rows, [("sep", "Fixes", "Fixes"), ("-", "Engine Fix", "Fixes"), ("+", "Plain Mod", "Fixes")])

    def test_build_text_list_detects_left_pane_order(self):
        # as some modlist websites show it: already in left-pane order, MO2 header comment last
        lol = "-Fixes_separator\n-Engine Fix\n+Plain Mod\n# This file was automatically generated by Mod Organizer.\n"
        info = lib.build_text_list("lol", {"modlist.txt": lol}, {"title": "LOL"})
        mods = json.loads((lib.LISTS / "lol" / "mods.json").read_text("utf-8"))
        self.assertEqual([m["name"] for m in mods], ["Engine Fix", "Plain Mod"])
        self.assertEqual(info["mods"], 2)
        # MO2 order gives the same result
        lib.build_text_list("mo2order", {"modlist.txt": MO2_MODLIST}, {})
        mods2 = json.loads((lib.LISTS / "mo2order" / "mods.json").read_text("utf-8"))
        self.assertEqual([m["name"] for m in mods2], ["Engine Fix", "Plain Mod"])

    def test_redact_ini_blanks_paths_and_gpu_only(self):
        src = ('[D]\nsScreenShotBaseName=F:\\x\\y\nsUNC=\\\\srv\\share\nsLocalSavePath=__MO_Saves\\\n'
               'sD3DDevice="GPU"\nfGamma=1.0\n; C:\\comment\n')
        out = lib.redact_ini(src)
        self.assertIn("sScreenShotBaseName=\n", out)
        self.assertIn("sUNC=\n", out)
        self.assertIn("sD3DDevice=\n", out)
        self.assertIn("sLocalSavePath=__MO_Saves\\", out)
        self.assertIn("fGamma=1.0", out)
        self.assertIn("; C:\\comment", out)

    def test_profile_file_name(self):
        self.assertEqual(lib.profile_file_name("MODLIST.TXT"), "modlist.txt")
        self.assertEqual(lib.profile_file_name("Fallout4Prefs.ini"), "Fallout4Prefs.ini")
        self.assertEqual(lib.profile_file_name("some/dir/Skyrim.ini"), "Skyrim.ini")
        # any path is reduced to its bare file name, so a result can never escape the list folder
        self.assertEqual(lib.profile_file_name("../../x.ini"), "x.ini")
        self.assertEqual(lib.profile_file_name("..\\..\\x.ini"), "x.ini")
        for bad in ("save.ess", "Skyrim.ini.BethINIbackup", ".hidden.ini", "notes.md", "a/b/", "..", "x.ini/"):
            self.assertIsNone(lib.profile_file_name(bad), bad)

    def test_nexus_domain(self):
        self.assertEqual(lib.nexus_domain("SkyrimSE"), "skyrimspecialedition")
        self.assertEqual(lib.nexus_domain("FalloutNV"), "newvegas")
        self.assertEqual(lib.nexus_domain("Fallout4"), "fallout4")
        self.assertEqual(lib.nexus_domain("Some New Game"), "somenewgame")
